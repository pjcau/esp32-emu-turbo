def _datasheets() -> dict[str, str]:
    """LCSC part number -> public URL of its datasheet, if one is present."""
    out: dict[str, str] = {}
    if not DATASHEETS.is_dir():
        return out
    for f in DATASHEETS.glob("*.pdf"):
        m = re.search(r"_(C\d+)\.pdf$", f.name)
        if m:
            out[m.group(1)] = f"/datasheets/{f.name}"
    return out


def build() -> str:
    sheets = _datasheets()
    rows = []
    with open(BOM, newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            lcsc = r["LCSC Part #"].strip()
            refs = r["Designator"].strip().strip('"')
            link = sheets.get(lcsc)
            rows.append((
                refs,
                r["Comment"].strip(),
                r["Footprint"].strip(),
                lcsc,
                r["Quantity"].strip(),
                _ROLES.get(lcsc, ""),
                f"[PDF]({link})" if link else "—",
            ))

    total = sum(int(r[4]) for r in rows)
    lines = [
        START,
        "",
        f"*{len(rows)} line items, {total} placements. Generated from "
        f"`release_jlcpcb/bom.csv` — the file uploaded to JLCPCB. "
        f"Regenerate with `make docs-bom`.*",
        "",
        "| Ref | Part | Package | LCSC | Qty | Role | Datasheet |",
        "|---|---|---|---|--:|---|---|",
    ]
    for refs, comment, fp, lcsc, qty, role, ds in rows:
        lines.append(
            f"| {refs} | {comment} | `{fp}` | "
            f"[{lcsc}](https://www.lcsc.com/product-detail/{lcsc}.html) | "
            f"{qty} | {role} | {ds} |"
        )
    lines += ["", END]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    table = build()
    text = DOC.read_text(encoding="utf-8")

    if START in text and END in text:
        new = re.sub(
            re.escape(START) + r".*?" + re.escape(END), table, text, flags=re.S)
    else:
        print(f"ERROR: markers not found in {DOC.relative_to(BASE)}.\n"
              f"Add these two lines where the table should go:\n"
              f"  {START}\n  {END}")
        return 1

    if "--check" in argv:
        if new != text:
            print(f"STALE: {DOC.relative_to(BASE)} does not match "
                  f"{BOM.relative_to(BASE)} — run `make docs-bom`")
            return 1
        print(f"OK: {DOC.relative_to(BASE)} matches the shipped BOM")
        return 0

    DOC.write_text(new, encoding="utf-8")
    n = table.count("\n| ") - 1
    print(f"Wrote the BOM table into {DOC.relative_to(BASE)} ({n} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

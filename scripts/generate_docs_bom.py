#!/usr/bin/env python3
"""Generate the docs BOM table from release_jlcpcb/bom.csv — the shipped BOM.

The table in website/docs/design/components.md was hand-maintained and had
drifted badly: it still listed the AMS1117 LDO and a C2 tantalum that no
longer exist, and it was missing U4, D1, Q1, L2, C29, C30, R22/R23, R24/R25
and R26 entirely. A hand-copied BOM is a second source of truth, and this
repo has already been bitten by that class of bug.

So the table is generated from the CSV that actually goes to JLCPCB, injected
between markers in the Markdown. Role descriptions live in _ROLES below,
keyed by LCSC part number — the one thing a CSV cannot tell you. Datasheet
links are discovered by matching the `_C<digits>.pdf` suffix of the files in
website/static/datasheets/, so adding a PDF is enough to link it.

`--check` fails when the rendered table differs from what is committed, so
the release pipeline can keep the docs honest.

Usage:
    python3 scripts/generate_docs_bom.py
    python3 scripts/generate_docs_bom.py --check
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
BOM = BASE / "release_jlcpcb" / "bom.csv"
DOC = BASE / "website" / "docs" / "design" / "components.md"
DATASHEETS = BASE / "website" / "static" / "datasheets"

START = "<!-- BOM:START — generated by scripts/generate_docs_bom.py -->"
END = "<!-- BOM:END -->"

